#!/usr/bin/env python3
"""Generate iss_worldmask.h - 1-bit landmask for the TFT ISS screen.

Source: data/Mapa swiata.bmp (480x320 24-bit). Land pixels (green/tan/white/
brown continents) are separated from water (dark blue) by colour, then the mask
is downsampled to the TFT map panel size (MW x MH) with a majority vote so thin
coastlines survive.

The result is a compact const array in firmware (no LittleFS dependency), used
by issRenderFrame() to draw the world map behind the ISS ground track - the same
look as the WWW "Satelity" page (data/satellite.js).

Run:  python3 tools/gen_worldmask.py
"""
import struct
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BMP = os.path.join(ROOT, "data", "Mapa swiata.bmp")
OUT = os.path.join(ROOT, "iss_worldmask.h")

MW, MH = 228, 114  # map panel size in the TFT ISS layout


def read_bmp(path):
    d = open(path, "rb").read()
    off = struct.unpack("<I", d[10:14])[0]
    w = struct.unpack("<i", d[18:22])[0]
    h = struct.unpack("<i", d[22:26])[0]
    bpp = struct.unpack("<H", d[28:30])[0]
    if bpp == 24:
        stride = ((w * 3 + 3) // 4) * 4
    elif bpp == 16:
        stride = ((w * 2 + 3) // 4) * 4
    else:
        sys.exit("expected 16- or 24-bit BMP, got %d" % bpp)
    return d, off, w, h, stride, bpp


def is_land(r, g, b):
    # Water is the dark blue background (blue channel clearly dominant).
    # Everything else (green/tan/brown/white continents) is land.
    return not (b >= r + 8 and b >= g + 8)


def main():
    d, off, w, h, stride, bpp = read_bmp(BMP)
    print("source %dx%d %dbpp" % (w, h, bpp))

    # majority-vote downsample into MW x MH
    mask = bytearray((MW * MH + 7) // 8)
    for j in range(MH):
        y0 = j * h // MH
        y1 = max(y0 + 1, (j + 1) * h // MH)
        for i in range(MW):
            x0 = i * w // MW
            x1 = max(x0 + 1, (i + 1) * w // MW)
            land = 0
            total = 0
            for y in range(y0, y1):
                ry = h - 1 - y  # BMP rows are bottom-up
                base = off + ry * stride
                for x in range(x0, x1):
                    if bpp == 24:
                        p = base + x * 3
                        r, g, b = d[p + 2], d[p + 1], d[p]
                    else:
                        v = d[base + x * 2] | (d[base + x * 2 + 1] << 8)
                        # RGB565 -> 8 bit, zeby prog is_land() byl ten sam co dla 24-bit
                        r5 = (v >> 11) & 0x1F
                        g6 = (v >> 5) & 0x3F
                        b5 = v & 0x1F
                        r = (r5 << 3) | (r5 >> 2)
                        g = (g6 << 2) | (g6 >> 4)
                        b = (b5 << 3) | (b5 >> 2)
                    if is_land(r, g, b):
                        land += 1
                    total += 1
            if total and land * 2 >= total:
                idx = j * MW + i
                mask[idx >> 3] |= 0x80 >> (idx & 7)

    with open(OUT, "w") as f:
        f.write("// Auto-generated by tools/gen_worldmask.py - do not edit.\n")
        f.write("// 1-bit landmask (bit=1 land) for the TFT ISS screen world map,\n")
        f.write("// derived from data/Mapa swiata.bmp. Size: %dx%d.\n" % (MW, MH))
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define ISS_WORLDMASK_W %d\n" % MW)
        f.write("#define ISS_WORLDMASK_H %d\n" % MH)
        f.write("static const uint8_t ISS_WORLDMASK[] = {\n")
        for k in range(0, len(mask), 16):
            f.write("  " + ",".join("0x%02X" % b for b in mask[k:k + 16]) + ",\n")
        f.write("};\n")
    print("wrote %s (%d bytes mask)" % (OUT, len(mask)))

    # ASCII preview
    for j in range(0, MH, 3):
        line = ""
        for i in range(MW):
            idx = j * MW + i
            line += "#" if mask[idx >> 3] & (0x80 >> (idx & 7)) else "."
        print(line)


if __name__ == "__main__":
    main()
