#!/usr/bin/env python3
"""Generate poland_mask.h - 1-bit landmask (bit=1 Poland) for the TFT RADIOSONDY screen.

Source: share/PL_map_raw.jpg (1536x1455, mapa drogowa Polski 1:750 000).
Poland = non-near-white pixels (kolorowa mapa) vs bialy margines wokol niej.
Downsampled to MPW x MPH majority vote so thin borders survive.

Result: compact const array in firmware (no LittleFS dependency), used by
drawRadiosondyScreen() to draw the Poland map behind sonde markers - the same
look as tools/render_radiosonda_v3.py makiety.

Run:  python3 tools/gen_poland_mask.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JPG = "/workspace/share/PL_map_raw.jpg"
if not os.path.exists(JPG):
    JPG = os.path.join(ROOT, "share", "PL_map_raw.jpg")
OUT = os.path.join(ROOT, "poland_mask.h")

MPW, MPH = 200, 120  # mask size; on TFT scaled to fit 480x287 (aspect 1.667)

MIN_BRIGHT = 238  # pixel >= this in all channels = white margin (not Poland)


def main():
    im = Image.open(JPG).convert("RGB")
    w, h = im.size
    print("source %dx%d" % (w, h))
    px = im.load()

    mask = bytearray((MPW * MPH + 7) // 8)
    for j in range(MPH):
        y0 = j * h // MPH
        y1 = max(y0 + 1, (j + 1) * h // MPH)
        for i in range(MPW):
            x0 = i * w // MPW
            x1 = max(x0 + 1, (i + 1) * w // MPW)
            land = 0
            total = 0
            for y in range(y0, y1):
                for x in range(x0, x1):
                    r, g, b = px[x, y]
                    if not (r >= MIN_BRIGHT and g >= MIN_BRIGHT and b >= MIN_BRIGHT):
                        land += 1
                    total += 1
            if total and land * 2 >= total:
                idx = j * MPW + i
                mask[idx >> 3] |= 0x80 >> (idx & 7)

    with open(OUT, "w") as f:
        f.write("// Auto-generated by tools/gen_poland_mask.py - do not edit.\n")
        f.write("// 1-bit map (bit=1 Poland) for the TFT RADIOSONDY screen,\n")
        f.write("// derived from PL_map_raw.jpg. Size: %dx%d.\n" % (MPW, MPH))
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define POLAND_MASK_W %d\n" % MPW)
        f.write("#define POLAND_MASK_H %d\n" % MPH)
        f.write("static const uint8_t POLAND_MASK[] = {\n")
        for k in range(0, len(mask), 16):
            f.write("  " + ",".join("0x%02X" % b for b in mask[k:k + 16]) + ",\n")
        f.write("};\n")
    print("wrote %s (%d bytes mask)" % (OUT, len(mask)))

    # ASCII preview
    for j in range(0, MPH, 4):
        line = ""
        for i in range(MPW):
            idx = j * MPW + i
            line += "#" if mask[idx >> 3] & (0x80 >> (idx & 7)) else "."
        print(line)


if __name__ == "__main__":
    main()