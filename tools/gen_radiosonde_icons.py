#!/usr/bin/env python3
"""Generuje radiosonde_icons.h - kolorowe ikony ekranu RADIOSONDY.

Zrodla (Fluent Emoji 3D, MIT):
  - Balloon:    https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets/Balloon/3D/balloon_3d.png
  - Automobile: https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets/Automobile/3D/automobile_3d.png

Kazda ikona: male (16x16 lub mniejsze, proporcje zachowane) RGB565.
Tlo przezroczyste = sentinel 0xF81F (magenta) - pomijane przy rysowaniu,
tak jak APRS_HOUSE_ICON w main.cpp.
"""
import os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, 'radiosonde_icons.h')

SENTINEL = 0xF81F
SIZE = 16  # maksymalny rozmiar znacznika (px)

SRC = {
    'BALLOON': '/tmp/balloon_3d.png',
    'AUTO':    '/tmp/auto_3d.png',
}


def to565(r, g, b):
    # rzutuj na int - numpy uint8 przesuwa modulo 256 i zeruje bity R/G
    r, g, b = int(r), int(g), int(b)
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def render(path):
    im = Image.open(path).convert('RGBA')
    bbox = im.getbbox()
    im = im.crop(bbox)
    # maksymalna kratka SIZE x SIZE z zachowaniem proporcji
    im.thumbnail((SIZE, SIZE), Image.LANCZOS)
    canvas = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
    canvas.alpha_composite(im, ((SIZE - im.width) // 2, (SIZE - im.height) // 2))
    a = np.asarray(canvas)
    out = np.full((SIZE, SIZE), SENTINEL, dtype=np.uint16)
    alpha = a[:, :, 3].astype(np.int16)
    mask = alpha >= 32  # plynny brzeg ponizej 32 -> sentinel
    rgb = a[:, :, :3][mask]
    out[mask] = [to565(r, g, b) for (r, g, b) in rgb]
    return out


def emit(arrays):
    lines = ['// Auto-generated by tools/gen_radiosonde_icons.py - NIE edytuj recznie.',
             '// Zrodla: Fluent Emoji 3D (MIT, microsoft/fluentui-emoji).',
             '// Male (16x16) kolorowe znaczniki sondy (balon) i lowcy (auto).',
             '// Sentinel 0xF81F = przezroczyste tlo (pomijane przy rysowaniu).',
             '#pragma once',
             '#include <stdint.h>',
             '']
    for name, arr in arrays:
        h, w = arr.shape
        lines.append('#define RS_ICON_%s_W %d' % (name, w))
        lines.append('#define RS_ICON_%s_H %d' % (name, h))
        lines.append('static const uint16_t RS_ICON_%s[%d] = {' % (name, arr.size))
        row = []
        for i, x in enumerate(arr.reshape(-1)):
            row.append('0x%04X,' % int(x))
            if (i + 1) % 16 == 0:
                lines.append('  ' + ''.join(row))
                row = []
        if row:
            lines.append('  ' + ''.join(row))
        lines.append('};')
        lines.append('')
    return '\n'.join(lines)


def main():
    arrays = [(n, render(p)) for n, p in SRC.items()]
    open(OUT_H, 'w').write(emit(arrays))
    print('zapisano %s (%dB)' % (OUT_H, os.path.getsize(OUT_H)))
    # podglad - zlozenie na zielonym tle (jak mapa) + powiekszenie
    from PIL import ImageDraw
    prev = Image.new('RGB', (SIZE * 2 + 6, SIZE * 2 + 6), (80, 140, 90))
    for i, (n, arr) in enumerate(arrays):
        img = Image.new('RGB', (SIZE, SIZE), (80, 140, 90))
        px = np.asarray(img).copy()
        for yy in range(SIZE):
            for xx in range(SIZE):
                c = arr[yy, xx]
                if c != SENTINEL:
                    r = (c >> 11) & 0x1F; g = (c >> 5) & 0x3F; b = c & 0x1F
                    px[yy, xx] = ((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2))
        img = Image.fromarray(px).resize((SIZE * 2, SIZE * 2), Image.NEAREST)
        prev.paste(img, (i * (SIZE * 2 + 3), 0))
    prev.save(ROOT + '/.mock/radiosonde_icons_preview.png')
    print('podglad: .mock/radiosonde_icons_preview.png')


if __name__ == '__main__':
    main()