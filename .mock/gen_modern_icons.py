#!/usr/bin/env python3
"""Generuje aprs_modern_icons.h - ikony ekranu APRS w stylu nowoczesnym.

24 symbole (bez HOUSE/WX, ktore rysuje sie z bitmapy w kodzie + plakietka):
  - 22 ikony z Fluent Emoji 3D (MIT) -> .mock/fluent3d/*.png
  - YAGI  -> .mock/cell_2_2.png  (#11 z yagi.jpg)
  - REPEATER -> .mock/cell_0_1.png (#2 z yagi.jpg)

Kazda ikona: 64x64 RGB565, tlo = kolor karty CARD (0x0884) -> wtapia sie w karte
bez sentinela/przezroczystosci (decoder BMP tego nie obsluguje, a my chcemy
zero dodatkowych bajtow w LittleFS).
"""
import os
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOCK = os.path.join(ROOT, '.mock')
F3 = os.path.join(MOCK, 'fluent3d')
OUT_H = os.path.join(ROOT, 'aprs_modern_icons.h')

SIZE = 64
CARD565 = 0x0884
# Rozwiniecie 565->8bit, zeby po powrocie 8bit->565 tlo bylo DOKLADNIE 0x0884.
def exp565(c):
    r = (c >> 11) & 0x1F; g = (c >> 5) & 0x3F; b = c & 0x1F
    return ((r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2))
CARD_RGB = exp565(CARD565)  # (8,16,33) -> 0x0884 po powrocie

YAGI_BG = np.array([120, 171, 192])  # tlo arkusza yagi.jpg

# symbol -> zrodlo ('f:<plik>' = fluent, 'c:<cell>' = wycinek z yagi.jpg)
MAP = [
    ("CAR",      "f:automobile.png"),
    ("TRUCK",    "f:delivery_truck.png"),
    ("VAN",      "f:minibus.png"),
    ("ROVER",    "f:automobile.png"),
    ("BIKE",     "f:bicycle.png"),
    ("HUMAN",    "f:pedestrian.png"),
    ("SHIP",     "f:passenger_ship.png"),
    ("GLIDER",   "f:parachute.png"),
    ("AMBUL",    "f:ambulance.png"),
    ("FIRETRK",  "f:fire_engine.png"),
    ("FIRE",     "f:fire.png"),
    ("HOSP",     "f:hospital.png"),
    ("DIGI",     "f:antenna_bars.png"),
    ("REPEATER", "c:cell_0_1.png"),
    ("YAGI",     "c:cell_2_2.png"),
    ("MICERPT",  "f:radio.png"),
    ("NODE",     "f:satellite.png"),
    ("LORA",     "f:radio.png"),
    ("LAPTOP",   "f:laptop.png"),
    ("LOGIN",    "f:mobile_phone.png"),
    ("GRID",     "f:globe_with_meridians.png"),
    ("EOC",      "f:office_building.png"),
    ("ICP",      "f:hut.png"),
    ("TRKSTOP",  "f:fuel_pump.png"),
]


def load_fluent(path):
    return Image.open(path).convert('RGBA')


def load_yagi_cell(path):
    """Wycina obiekt z arkusza yagi.jpg z miekka maska alfa."""
    im = Image.open(path).convert('RGB')
    a = np.asarray(im).astype(np.int16)
    d = np.abs(a - YAGI_BG).sum(axis=2)              # odleglosc od tla
    lo, hi = 40, 120
    alpha = np.clip((d - lo) * 255.0 / (hi - lo), 0, 255).astype(np.uint8)
    mask = Image.fromarray(alpha, 'L').filter(ImageFilter.MaxFilter(3))
    out = im.convert('RGBA'); out.putalpha(mask)
    return out.crop(mask.getbbox())


def to565(rgb):
    r, g, b = rgb
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def render(spec):
    if spec.startswith('f:'):
        icon = load_fluent(os.path.join(F3, spec[2:]))
    else:
        icon = load_yagi_cell(os.path.join(MOCK, spec[2:]))
    # Skaluj z zachowaniem proporcji, wysrodkuj, zloz na kolor karty.
    icon = icon.copy()
    icon.thumbnail((SIZE - 4, SIZE - 4), Image.LANCZOS)
    canvas = Image.new('RGBA', (SIZE, SIZE), CARD_RGB + (255,))
    canvas.alpha_composite(icon, ((SIZE - icon.width) // 2, (SIZE - icon.height) // 2))
    arr = np.asarray(canvas.convert('RGB')).astype(np.uint16)
    v = ((arr[:, :, 0] & 0xF8) << 8) | ((arr[:, :, 1] & 0xFC) << 3) | (arr[:, :, 2] >> 3)
    return v, canvas.convert('RGB')


def emit_header(arrays):
    lines = []
    lines.append('// Auto-generated by .mock/gen_modern_icons.py - NIE edytuj recznie.')
    lines.append('// Ikony ekranu APRS w stylu nowoczesnym (drawAprsAlertModern).')
    lines.append('// 64x64 RGB565, tlo = kolor karty (0x0884), wiec wtapiaja sie w karte.')
    lines.append('// Zrodla: Fluent Emoji 3D (MIT) + wycinki z yagi.jpg (#2 repeater, #11 yagi).')
    lines.append('// W firmware, a nie w LittleFS - nie zabiera miejsca na uploady z WWW.')
    lines.append('#pragma once')
    lines.append('#include <stdint.h>')
    lines.append('')
    lines.append('#define APRS_MODERN_ICON_W 64')
    lines.append('#define APRS_MODERN_ICON_H 64')
    lines.append('')
    for name, v in arrays:
        flat = v.reshape(-1)
        lines.append('static const uint16_t APRS_MICON_%s[%d] = {' % (name, flat.size))
        row = []
        for i, x in enumerate(flat):
            row.append('0x%04X,' % int(x))
            if (i + 1) % 16 == 0:
                lines.append('  ' + ''.join(row)); row = []
        if row:
            lines.append('  ' + ''.join(row))
        lines.append('};')
        lines.append('')
    return '\n'.join(lines) + '\n'


def main():
    arrays = []
    preview = Image.new('RGB', (6 * 72 + 12, 4 * 72 + 40), (11, 18, 32))
    from PIL import ImageDraw, ImageFont
    dr = ImageDraw.Draw(preview)
    try:
        f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 11)
    except Exception:
        f = ImageFont.load_default()
    dr.text((8, 8), 'aprs_modern_icons.h - 24 ikony 64x64 RGB565 (tak wygladaja na karcie)', font=f, fill=(84, 214, 190))
    for i, (name, spec) in enumerate(MAP):
        v, rgb = render(spec)
        arrays.append((name, v))
        c, r = divmod(i, 6)
        x, y = 12 + c * 72, 30 + r * 72
        preview.paste(rgb, (x, y))
        dr.text((x, y + 66), name, font=f, fill=(239, 247, 239))
    open(OUT_H, 'w').write(emit_header(arrays))
    preview.save(os.path.join(MOCK, 'modern_icons_header_preview.png'))
    print('zapisano %s (%d ikon)' % (OUT_H, len(arrays)))
    print('podglad: .mock/modern_icons_header_preview.png')


if __name__ == '__main__':
    main()
